-- 대표님 11-05: 박지 정보창에 산불조심기간 입산통제 띠를 단다.
-- 앱이 산림청에 직접 묻지 않고, 봄·가을 공고가 나오면 산림청 '입산 가능 지역 안내'
-- 지도의 입산통제구역 그림에 박지 좌표를 맞대 본 결과를 여기에 넣는다(점검 방법은 TASK_FIRE_CLOSURE.md).
--   level: in(통제구역 안) · edge(박지 둘레 10m 일부가 통제구역) · near(200m 안)
--   정보창은 오늘이 starts_on~ends_on 안일 때만 띠를 보인다. 기간이 지나면 저절로 사라진다.
-- 통제 여부는 공개 안내라 비회원도 읽는다(좌표는 없다). 쓰기는 SQL 편집기에서만.
-- 여러 번 실행해도 안전(같은 철 자료는 덮어쓴다).
-- =========================================================================

CREATE TABLE IF NOT EXISTS public.spot_fire_closures (
  spot_id text NOT NULL REFERENCES public.spots(id) ON DELETE CASCADE,
  season text NOT NULL,
  starts_on date NOT NULL,
  ends_on date NOT NULL,
  level text NOT NULL CHECK (level IN ('in', 'edge', 'near')),
  distance_m integer,
  checked_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (spot_id, season)
);
CREATE INDEX IF NOT EXISTS spot_fire_closures_period ON public.spot_fire_closures (ends_on, starts_on);
ALTER TABLE public.spot_fire_closures ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.spot_fire_closures FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.spot_fire_closures TO anon, authenticated;
DROP POLICY IF EXISTS spot_fire_closures_read ON public.spot_fire_closures;
CREATE POLICY spot_fire_closures_read ON public.spot_fire_closures FOR SELECT USING (true);

