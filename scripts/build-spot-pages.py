def sitemap(ids, extra=()):
    today = date.today().isoformat()
    urls = [f"  <url>\n    <loc>{SITE}/</loc>\n    <lastmod>{today}</lastmod>\n  </url>",
            f"  <url>\n    <loc>{SITE}/map.html</loc>\n    <lastmod>{today}</lastmod>\n  </url>",
            f"  <url>\n    <loc>{SITE}/spot/</loc>\n    <lastmod>{today}</lastmod>\n  </url>"]
    urls += [f"  <url>\n    <loc>{SITE}{p}</loc>\n    <lastmod>{today}</lastmod>\n  </url>" for p in extra]
    urls += [f"  <url>\n    <loc>{SITE}/spot/{i}/</loc>\n  </url>" for i in ids]
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(urls) + "\n</urlset>\n")


def write(path, text, dry):
    if dry:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    dry = "--dry-run" in sys.argv
    rows = [r for r in fetch_spots() if str(r.get("id") or "").strip() and clean_text(r.get("spot_main"))]
    manual = load_excluded_ids()
    park, kept = [], []
    for r in rows:
        sid = str(r["id"]).strip()
        if sid in manual:
            continue
        if PARK_RE.search(r.get("view_brief") or ""):
            park.append(r)
            continue
        kept.append(r)

    by_region = {}
    for r in kept:
        by_region.setdefault(region_of(r), []).append(r)
    for lst in by_region.values():
        lst.sort(key=lambda r: " ".join(display_name(r)))
    order = [g for g in REGION_ORDER if g in by_region] + sorted(g for g in by_region if g not in REGION_ORDER)
    groups = [(g, by_region[g]) for g in order]

    spot_themes = {id(r): themes_of(r) for r in kept}
    theme_rows = {s: [r for r in kept if s in spot_themes[id(r)]] for s, _ in THEMES}
    theme_counts = {s: len(v) for s, v in theme_rows.items()}

    keep_ids = set()
    for r in kept:
        sid = str(r["id"]).strip()
        keep_ids.add(sid)
        peers = [p for p in by_region[region_of(r)] if p is not r][:8]
        write(os.path.join(OUT_DIR, sid, "index.html"),
              spot_page(r, peers, len(by_region[region_of(r)]) - 1, spot_themes[id(r)]), dry)
    write(os.path.join(OUT_DIR, "index.html"), index_page(groups, len(kept), theme_counts), dry)

    extra = []
    for s, _ in THEMES:
        if theme_rows[s]:
            write(os.path.join(THEME_DIR, s, "index.html"), theme_page(s, theme_rows[s], order), dry)
            extra.append(f"/theme/{s}/")
    for g, rows_g in groups:
        if g in REGION_SLUG:
            write(os.path.join(REGION_DIR, REGION_SLUG[g], "index.html"), region_page(g, rows_g, theme_rows), dry)
            extra.append(f"/region/{REGION_SLUG[g]}/")

    # 제외됐거나 DB에서 사라진 박지 페이지 삭제 (숫자 id 폴더 중 이 스크립트가 만든 것만)
    removed = []
    if os.path.isdir(OUT_DIR):
        for name in os.listdir(OUT_DIR):
            p = os.path.join(OUT_DIR, name)
            if not os.path.isdir(p) or name in keep_ids:
                continue
            idx = os.path.join(p, "index.html")
            if os.path.exists(idx) and GENERATED_MARK in open(idx, encoding="utf-8").read(400):
                removed.append(name)
                if not dry:
                    shutil.rmtree(p)

    ids_sorted = sorted(keep_ids, key=lambda x: (not x.isdigit(), int(x) if x.isdigit() else 0, x))
    write(os.path.join(ROOT, "sitemap.xml"), sitemap(ids_sorted, extra), dry)
    write(os.path.join(ROOT, "llms.txt"), llms_txt(groups, len(kept), theme_counts), dry)

    print("themes " + ", ".join(f"{THEME_LABEL[s]} {c}" for s, c in theme_counts.items()))
    print(f"spots {len(rows)} | pages {len(kept)} | list pages {len(extra)} | park-excluded {len(park)} | manual-excluded {len(manual)} | removed {len(removed)}"
          + (" (dry-run)" if dry else ""))
    if park:
        print("park-excluded:", ", ".join(f'{r["id"]}:{clean_text(r.get("spot_main"))}' for r in park))


if __name__ == "__main__":
    main()
