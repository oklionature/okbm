def spot_page(row, same_region):
    sid = str(row["id"]).strip()
    main, sub = display_name(row)
    city = clean_text(row.get("cityName"))
    region = region_of(row)
    brief = clean_text(row.get("view_brief"))
    d, d_label, d_class = difficulty_of(row)
    elev = fmt_num(row.get("elevation"))
    dist = fmt_num(row.get("distance_km"))
    course = clean_text(row.get("course_type"))
    terrains = terrains_of(row)

    name_full = f"{main} {sub}".strip()
    place = city or region
    title = f"{name_full} 백패킹 - {place} | 낭만루트"
    desc = brief if len(brief) <= 150 else brief[:149].rstrip() + "…"
    if not desc:
        desc = f"{place} {name_full} 백패킹 장소 정보. 낭만루트에서 들머리와 코스를 확인하세요."
    page_url = f"{SITE}/spot/{sid}/"
    map_url = f"{SITE}/map.html?id={urllib.parse.quote(sid)}"
    qr_url = ("https://api.qrserver.com/v1/create-qr-code/?size=320x320&margin=8&data="
              + urllib.parse.quote(map_url, safe=""))

    badges = [f'<li>{esc(region)}{(" · " + esc(city)) if city and city != region else ""}</li>']
    if elev:
        badges.append(f"<li>해발 {esc(elev)}m</li>")
    badges.append(f'<li class="{d_class}">난이도 {esc(d_label)} ({d}/5)</li>')
    if dist:
        badges.append(f"<li>편도 약 {esc(dist)}km</li>" if course == "편도" else f"<li>거리 약 {esc(dist)}km</li>")
    if course and course != "일반":
        badges.append(f"<li>{esc(course)} 코스</li>")
