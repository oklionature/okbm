def theme_page(slug, rows, region_order):
    label = THEME_LABEL[slug]
    n = len(rows)
    by_region = {}
    for r in rows:
        by_region.setdefault(region_of(r), []).append(r)
    order = [g for g in region_order if g in by_region]
    intro = THEME_INTRO[slug].format(N=n)
    top = sorted(order, key=lambda g: -len(by_region[g]))[:3]
    faqs = []
    if len(top) >= 2:
        rest = ", ".join(f"{region_word(g)} {len(by_region[g])}곳" for g in top[1:])
        q_name = "퇴근박 하기 좋은 박지" if slug == "afterwork" else THEME_NAME[slug]
        faqs.append((f"{q_name}{josa(q_name, '이', '가')} 가장 많은 지역은 어디예요?",
                     f"{region_word(top[0])}{josa(region_word(top[0]), '이', '가')} {len(by_region[top[0]])}곳으로 가장 많고 "
                     f"그다음은 {rest} 순이에요."))
    faqs.append(LOCATION_FAQ)
    nav = chips([(f"/theme/{s}/", THEME_LINK[s]) for s, _ in THEMES if s != slug]
                + [(f"/region/{REGION_SLUG[g]}/", f"{region_word(g)} 백패킹") for g in REGION_ORDER])
    return list_page(
        path=f"/theme/{slug}/", title=f"{label} 백패킹 장소 {n}곳 - 전국 {THEME_NAME[slug]} | 낭만루트",
        h1=f"{label} 백패킹 장소 {n}곳", desc=short_desc(f"{intro} {LIST_NOTE}"), intro=intro,
        crumb_name=THEME_NAME[slug], faqs=faqs,
        sections=[(region_word(g), sorted(by_region[g], key=lambda r: " ".join(display_name(r))), False) for g in order],
        nav_links=nav)


def region_page(region, rows, theme_rows):
    word = region_word(region)
    n = len(rows)
    ids = {id(r) for r in rows}
    in_theme = {s: [r for r in theme_rows[s] if id(r) in ids] for s, _ in THEMES}
    deck, easy = len(in_theme["deck"]), in_theme["beginner"]
    intro = f"{word}에는 낭만루트에 등록된 백패킹 박지가 {n}곳 있어요."
    parts = ([f"데크가 있는 곳이 {deck}곳"] if deck else []) + ([f"초보도 가기 쉬운 곳이 {len(easy)}곳"] if easy else [])
    if parts:
        intro += " 그중 " + ", ".join(parts) + "이에요."
    faqs = []
    if easy:
        names = sorted(easy, key=lambda r: km_of(r) or 0)[:3]
        picks = ", ".join(re.sub(r"\s*\([^)]*\)\s*$", "", " ".join(display_name(r)).strip()) for r in names)
        faqs.append((f"{word}에서 초보가 가기 좋은 박지는 어디예요?",
                     f"{picks}처럼 난이도가 쉽고 들머리에서 1km 안쪽만 걸으면 되는 곳이 {len(easy)}곳 있어요."))
    faqs.append(LOCATION_FAQ)
    by_city = {}
    for r in rows:
        by_city.setdefault(clean_text(r.get("cityName")) or word, []).append(r)
    cities = sorted(by_city, key=lambda c: (-len(by_city[c]), c))
    nav = chips([(f"/region/{REGION_SLUG[g]}/", f"{region_word(g)} 백패킹") for g in REGION_ORDER if g != region]
                + [(f"/theme/{s}/", f"{THEME_LINK[s]}") for s, _ in THEMES])
    return list_page(
        path=f"/region/{REGION_SLUG[region]}/", title=f"{word} 백패킹 장소 {n}곳 - {word} 박지 추천 | 낭만루트",
        h1=f"{word} 백패킹 장소 {n}곳", desc=short_desc(f"{intro} {LIST_NOTE}"), intro=intro,
        crumb_name=word, faqs=faqs,
        sections=[(c, sorted(by_city[c], key=lambda r: " ".join(display_name(r))), False) for c in cities],
        nav_links=nav)


