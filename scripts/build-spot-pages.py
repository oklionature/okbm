def spot_item(r, small_region=False):
    d, d_label, _ = difficulty_of(r)
    elev = fmt_num(r.get("elevation"))
    meta = [clean_text(r.get("cityName")) or region_of(r)]
    if small_region:
        meta.insert(0, region_word(region_of(r)))
    meta.append(f"난이도 {d_label}")
    if elev:
        meta.append(f"해발 {elev}m")
    return (f'<li><a href="/spot/{esc(r["id"])}/">{esc(" ".join(display_name(r)).strip())}'
            f'<small>{esc(" · ".join(meta))}</small></a></li>')


def short_desc(s, limit=150):
    return s if len(s) <= limit else s[:limit - 1].rstrip() + "…"


def chips(links):
    return '<ul class="chips">' + "".join(f'<li><a href="{esc(h)}">{esc(t)}</a></li>' for h, t in links) + "</ul>"


