ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://romanticroute.kr"
OUT_DIR = os.path.join(ROOT, "spot")
EXCLUDE_FILE = os.path.join(ROOT, "scripts", "spot-pages-exclude.json")
SELECT = ("id,region,cityName,spot_main,spot_sub,elevation,terrain,difficulty,"
          "distance_km,course_type,view_brief,created_at")
PARK_RE = re.compile(r"(국립|도립|군립)공원")
REGION_ORDER = ["서울/인천", "경기", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"]
REGION_ALIAS = {"서울": "서울/인천", "인천": "서울/인천", "대전": "충남", "세종": "충남",
                "대구": "경북", "부산": "경남", "울산": "경남", "광주": "전남"}
GENERATED_MARK = "<!-- generated by scripts/build-spot-pages.py -->"


def supabase_config():
    url = os.environ.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_PUBLISHABLE_KEY") or os.environ.get("SUPABASE_ANON_KEY")
    if url and key:
        return url, key
    # 사이트에 이미 공개된 publishable 키를 그대로 쓴다 (anon 권한 = 공개 컬럼만 읽힘)
    src = open(os.path.join(ROOT, "map.html"), encoding="utf-8").read()
    url = re.search(r"window\.SUPABASE_URL = '([^']+)'", src).group(1)
    key = re.search(r"window\.SUPABASE_ANON_KEY = '([^']+)'", src).group(1)
    return url, key


def fetch_spots():
    url, key = supabase_config()
    req = urllib.request.Request(
        f"{url}/rest/v1/spots?select={SELECT}&order=id.asc",
        headers={"apikey": key, "Authorization": "Bearer " + key},
    )
    with urllib.request.urlopen(req, timeout=30) as res:
        return json.load(res)


def load_excluded_ids():
    if not os.path.exists(EXCLUDE_FILE):
        return set()
    data = json.load(open(EXCLUDE_FILE, encoding="utf-8"))
    return {str(x).strip() for x in data.get("ids", [])}


def region_of(row):
    r = str(row.get("region") or "").strip()
    return REGION_ALIAS.get(r, r) or "기타"


def clean_text(s):
    return re.sub(r"\s+", " ", str(s or "").replace("\\n", "\n")).strip()


def fmt_num(v):
    if v is None or v == "":
        return ""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v).strip()
    return str(int(f)) if f == int(f) else f"{f:.1f}".rstrip("0").rstrip(".")


def difficulty_of(row):
    try:
        d = int(str(row.get("difficulty") or "3").strip())
    except ValueError:
        d = 3
    d = min(max(d, 1), 5)
    if d <= 2:
        return d, "쉬움", "easy"
    if d >= 4:
        return d, "어려움", "hard"
    return d, "보통", "mid"


def terrains_of(row):
    return [t.strip() for t in str(row.get("terrain") or "").split(",") if t.strip()]


def display_name(row):
    main = clean_text(row.get("spot_main"))
    sub = clean_text(row.get("spot_sub"))
    if sub and sub in main:
        sub = ""
    return main, sub


def esc(s):
    return html.escape(str(s), quote=True)


def json_ld(obj):
    # </script> 조기 종료 방지
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


