#!/usr/bin/env python3
"""박지별 검색용 정적 페이지(spot/<id>/index.html), 목록(spot/index.html), sitemap.xml을 만든다.

    python3 scripts/build-spot-pages.py            # 생성
    python3 scripts/build-spot-pages.py --dry-run  # 파일을 쓰지 않고 요약만

공개 범위: 이름·지역·[뷰/특징](view_brief)·고도·지형·난이도·거리·코스 유형만.
좌표·들머리 주소·코스/피칭/팁·작성자 SNS·사용자 사진은 넣지 않는다. 상세는 map.html?id=<id>로 넘긴다.

제외:
  - view_brief에 국립·도립·군립공원이 언급된 박지 (공원 내 야영 금지, 검색 홍보 방지)
  - scripts/spot-pages-exclude.json 의 "ids"에 적은 박지
제외되거나 DB에서 사라진 박지의 기존 페이지는 지운다.
"""
